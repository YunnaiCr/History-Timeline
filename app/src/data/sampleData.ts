import { toJdn, bcToJdn } from "../lib/time";

export interface Category {
  id: string;
  name: string;
  color: string;
}

export interface Tag {
  id: string;
  name: string;
}

export interface TimelineEvent {
  id: string;
  title: string;
  /** 起止（点事件时 endJdn 省略） */
  startJdn: number;
  endJdn?: number;
  /** 原始模糊文本，如 "约公元前1046年" */
  dateText: string;
  categoryId: string;
  tagIds: string[];
  summary: string;
  importance: 1 | 2 | 3; // 1 高 / 2 中 / 3 低，低缩放时只显示高重要度

  /**
   * 父事件 id。用于"事件嵌套"：甲午战争 → 黄海海战 / 威海卫保卫战。
   * 规则：父事件是区间事件，子事件的时间必须落在父区间内（由 validateHierarchy 校验）。
   * 一级子事件用 parentId，更深层用 "p:父id/孙id" 表示全部祖先（便于生成 span path）。
   */
  parentId?: string;
  /**
   * 展开策略（决定父事件展开时子事件如何出现）：
   *  - "span"      默认。父事件画成一条带，子事件折叠进父带来的"明细条"，放大后沿带排列
   *  - "point"     父事件只画点，子事件在父点上方/下方成列展开
   *  - "collapsed" 默认折叠，点击父事件才展开
   */
  expandMode?: "span" | "point" | "collapsed";
  /** 手动指定颜色，缺省用类别色 */
  color?: string;
}

